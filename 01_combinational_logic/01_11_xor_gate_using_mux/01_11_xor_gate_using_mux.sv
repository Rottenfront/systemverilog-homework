module xor_gate_using_mux
(
    input  a,
    input  b,
    output o
);


    logic nota;
    mux mux1 (
        .d0(1),
        .d1(0),
        .sel(a),
        .y(nota)
    );
    mux mux2 (
        .d0(a),
        .d1(nota),
        .sel(b),
        .y(o)
    );

endmodule
